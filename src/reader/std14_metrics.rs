//! Standard 14 font metrics (ISO 32000-1 §9.6.2.2): glyph advance widths
//! in thousandths of text space, generated from the Adobe Font Metrics
//! files Adobe publishes for the core fonts (data tables, AFM `WX`
//! fields) by `gen_std14.py`; the Unicode keys come from the staged
//! Adobe Glyph List subset (`docs/document/pdf/agl/subset.txt`).
//!
//! Each font carries its built-in encoding as `by_code` (the AFM `C`
//! field — StandardEncoding for the Latin faces, the Symbol and
//! ZapfDingbats sets for those two) and `by_unicode` for lookups
//! through a PDF-supplied `/Encoding`. Both slices are sorted.

/// One standard-14 face's metrics.
#[derive(Debug)]
