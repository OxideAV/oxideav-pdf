/// Resolve a `/BaseFont` name to one of the standard 14 faces.
///
/// Strips a subset tag (`ABCDEF+`), accepts the names ISO 32000-1
/// §9.6.2.2 lists and the aliases readers have always honoured
/// (Arial → Helvetica, TimesNewRoman → Times, CourierNew → Courier,
/// with `,Bold` / `-BoldMT` / `-Italic` / `Oblique` style suffixes in
/// any of their spellings).
pub(crate) fn resolve(base_font: &str) -> Option<&'static Std14Metrics> {
    let name = match base_font.split_once('+') {
        Some((tag, rest)) if tag.len() == 6 && tag.bytes().all(|b| b.is_ascii_uppercase()) => rest,
        _ => base_font,
    };
    let lower = name.to_ascii_lowercase();
    let bold = lower.contains("bold")
        || lower.contains("black")
        || lower.contains("heavy")
        || lower.contains("semibold");
    let italic = lower.contains("italic") || lower.contains("oblique");
    let family = if lower.starts_with("courier") || lower.contains("mono") {
        "Courier"
    } else if lower.starts_with("times") {
        "Times"
    } else if lower.starts_with("helvetica") || lower.starts_with("arial") {
        "Helvetica"
    } else if lower.starts_with("symbol") {
        return Some(&SYMBOL);
    } else if lower.starts_with("zapfdingbats") || lower.starts_with("dingbats") {
        return Some(&ZAPFDINGBATS);
    } else {
        return None;
    };
    let full = match (family, bold, italic) {
        ("Times", false, false) => "Times-Roman",
        ("Times", true, false) => "Times-Bold",
        ("Times", false, true) => "Times-Italic",
        ("Times", true, true) => "Times-BoldItalic",
        ("Helvetica", false, false) => "Helvetica",
        ("Helvetica", true, false) => "Helvetica-Bold",
        ("Helvetica", false, true) => "Helvetica-Oblique",
        ("Helvetica", true, true) => "Helvetica-BoldOblique",
        ("Courier", false, false) => "Courier",
        ("Courier", true, false) => "Courier-Bold",
        ("Courier", false, true) => "Courier-Oblique",
        _ => "Courier-BoldOblique",
    };
    ALL.iter().copied().find(|f| f.name == full)
}

impl Std14Metrics {
    /// Width of the glyph at `code` under the font's built-in encoding.
    pub(crate) fn width_by_code(&self, code: u8) -> Option<u16> {
        self.by_code
            .binary_search_by_key(&code, |(c, _)| *c)
            .ok()
            .map(|i| self.by_code[i].1)
    }

    /// Width of the glyph whose Unicode text is `text`.
    pub(crate) fn width_by_unicode(&self, text: &str) -> Option<u16> {
        self.by_unicode
            .binary_search_by(|(t, _)| (*t).cmp(text))
            .ok()
            .map(|i| self.by_unicode[i].1)
    }

    /// Whether this face uses its own built-in encoding rather than
    /// StandardEncoding (Symbol, ZapfDingbats).
    pub(crate) fn is_symbolic(&self) -> bool {
        self.name == "Symbol" || self.name == "ZapfDingbats"
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn aliases_resolve_to_the_core_faces() {
        assert_eq!(resolve("Arial,Bold").unwrap().name, "Helvetica-Bold");
        assert_eq!(
            resolve("ABCDEF+TimesNewRomanPS-BoldItalicMT").unwrap().name,
            "Times-BoldItalic"
        );
        assert_eq!(resolve("CourierNewPSMT").unwrap().name, "Courier");
        assert_eq!(resolve("Symbol").unwrap().name, "Symbol");
        assert!(resolve("CMR10").is_none());
    }

    #[test]
    fn widths_match_the_afm_tables() {
        let t = resolve("Times-Roman").unwrap();
        assert_eq!(t.width_by_unicode(" "), Some(250));
        assert_eq!(t.width_by_unicode("W"), Some(944));
        assert_eq!(t.width_by_code(b'W'), Some(944));
        assert_eq!(resolve("Courier").unwrap().width_by_unicode("i"), Some(600));
        // Symbol's built-in encoding: code 0x6D is mu.
        assert_eq!(resolve("Symbol").unwrap().width_by_code(0x6D), Some(576));
        for f in ALL {
            assert!(
                f.by_code.windows(2).all(|w| w[0].0 < w[1].0),
                "{} by_code sorted",
                f.name
            );
            assert!(
                f.by_unicode.windows(2).all(|w| w[0].0 < w[1].0),
                "{} by_unicode sorted",
                f.name
            );
        }
    }
}
